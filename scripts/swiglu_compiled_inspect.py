"""Inspect generated SwiGLU source and the actual selected PyTorch2.5.1 launcher."""

import argparse
from datetime import datetime, timezone
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys

import torch

from rmsnorm_compiled_inspect import extract_kernels, selected_launchers

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tokens", type=int, default=16)
    parser.add_argument("--hidden", type=int, default=8960)
    args = parser.parse_args()
    shape = (args.tokens, args.hidden)
    if not torch.cuda.is_available():
        parser.error("CUDA required")
    if torch.__version__.split("+")[0] != "2.5.1":
        parser.error("private inspection helpers require the pinned PyTorch2.5.1")
    from torch._inductor import config
    from torch._inductor.utils import run_and_get_code
    from fastinfer.kernels.swiglu import reference_swiglu
    from fastinfer.kernels.triton_swiglu import swiglu, _swiglu, BLOCK_SIZE, NUM_WARPS
    import triton

    shapes = ((1, 65), (1, 1536), (1, 8960), (16, 8960), (128, 8960))
    if shape not in shapes:
        parser.error("select one of the five benchmark shapes")
    torch.manual_seed(2)
    for current in shapes:
        gate = 2 * torch.randn(current, device="cuda", dtype=torch.float16)
        up = torch.randn_like(gate)
        if current == shape:
            break
    print(f"Inspecting shape={shape}...", flush=True)
    torch.compiler.reset()
    compiled = torch.compile(reference_swiglu, backend="inductor", fullgraph=True,
                             dynamic=False, options={"triton.cudagraphs": False})
    with torch.inference_mode(), config.patch({"force_disable_caches": True}):
        actual, sources = run_and_get_code(compiled, gate, up)
        expected = reference_swiglu(gate, up)
        oracle_activation = (gate.double() * torch.sigmoid(gate.double())).to(gate.dtype)
        oracle = (oracle_activation.double() * up.double()).to(gate.dtype)
        for output in (actual, swiglu(gate, up, block_size=BLOCK_SIZE, num_warps=NUM_WARPS)):
            for reference in (expected, oracle):
                torch.testing.assert_close(output, reference, rtol=.002, atol=2e-4)
        resource_output = torch.empty_like(gate)
        programs = triton.cdiv(gate.numel(), BLOCK_SIZE)
        handle = _swiglu[(programs,)](
            gate, up, resource_output, gate.numel(), BLOCK_SIZE,
            num_warps=NUM_WARPS, enable_fp_fusion=False,
        )
        torch.cuda.synchronize()
    if not sources:
        raise RuntimeError("generated source unavailable; no scheduling conclusion possible")
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    destination = ROOT / "results/raw" / f"swiglu_generated_{stamp}"
    destination.mkdir(parents=True)
    report = {
        "shape": list(shape), "seed": 2, "accuracy_passed": True,
        "environment": json.loads(subprocess.check_output(
            [sys.executable, str(ROOT / "scripts/environment_report.py")], cwd=ROOT, text=True)),
        "scope": "Code/resource inspection, not timing or causal proof. "
                 "Compiler caches disabled during inspection; benchmark settings unchanged. "
                 "Read selected runtime launchers rather than decorator candidates.",
        "source_sha256": {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
                          for name in ("scripts/swiglu_compiled_inspect.py", "kernels/swiglu.py",
                                       "kernels/triton_swiglu.py", "scripts/rmsnorm_compiled_inspect.py")},
        "manual_resources": {"programs": programs, "block_size": BLOCK_SIZE,
                             "num_warps": NUM_WARPS, "registers_per_thread": handle.n_regs,
                             "spills": handle.n_spills, "shared_bytes": handle.metadata.shared},
        "sources": [],
    }
    for index, source in enumerate(sources):
        path = destination / f"compiled_{index}.py"
        path.write_text(source)
        extracted = extract_kernels(source)
        # Execute only the trusted wrapper just generated by this compiler run.
        spec = importlib.util.spec_from_file_location(f"fastinfer_generated_swiglu_{index}", path)
        module = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = module
        spec.loader.exec_module(module)
        with torch.inference_mode():
            replay = module.call([gate, up])
            torch.cuda.synchronize()
            for reference in (expected, oracle):
                torch.testing.assert_close(replay[0], reference, rtol=.002, atol=2e-4)
        launchers = selected_launchers(vars(module), gate.numel())
        for launcher in launchers:
            launcher["programs_from_flat_xblock"] = launcher.pop("programs_from_xblock", None)
        extracted["selected_runtime_launchers"] = launchers
        report["sources"].append({"path": str(path),
                                  "sha256": hashlib.sha256(source.encode()).hexdigest(), **extracted})
        for kernel in extracted["kernel_definitions"]:
            print(f"\nGenerated kernel: {kernel['name']}\n{kernel['source']}", flush=True)
        print("Selected runtime launchers:", flush=True)
        print(json.dumps(launchers, indent=2), flush=True)
        print("Wrapper launches:", flush=True)
        for launch in extracted["wrapper_launches"]:
            print(launch, flush=True)
    print("Manual resources:", json.dumps(report["manual_resources"]), flush=True)
    (destination / "summary.json").write_text(json.dumps(report, indent=2) + "\n")
    print(f"Saved: {destination}", flush=True)


if __name__ == "__main__":
    main()
